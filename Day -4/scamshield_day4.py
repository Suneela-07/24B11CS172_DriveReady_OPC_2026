from pydantic import BaseModel, Field
from typing import Literal, List

class ScamAnalysis(BaseModel):

    risk_level: Literal[
        "Safe",
        "Suspicious",
        "Dangerous"
    ] = Field(description="Overall risk classification")

    confidence: float = Field(
        ge=0,
        le=1,
        description="Confidence score between 0 and 1"
    )

    summary: str = Field(
        description="Short explanation of the message"
    )

    suspicious_signals: List[str] = Field(
        description="Suspicious words, patterns, or behaviours"
    )

    extracted_urls: List[str] = Field(
        description="URLs present in the message"
    )

    recommended_actions: List[str] = Field(
        description="Safety steps recommended to the user"
    )

print("ScamShield Pydantic model created successfully!")

structured_llm = llm.with_structured_output(ScamAnalysis)

print("Structured output initialized successfully!")

def analyze_message_structured(message):

    urls = extract_urls.invoke({
        "message": message
    })

    reputation_results = []

    for url in urls:
        result = check_url_reputation.invoke({
            "url": url
        })

        reputation_results.append(result)

    prompt = f"""
    You are ScamShield, a cybersecurity scam detection assistant.

    Analyze this message carefully.

    MESSAGE:
    {message}

    EXTRACTED URLS:
    {urls}

    URL REPUTATION RESULTS:
    {reputation_results}

    RULES:
    1. Detect urgency, threats, fake rewards, and suspicious requests.
    2. Identify requests for passwords, OTPs, banking details, or payments.
    3. Consider URL reputation results.
    4. A URL not found in URLhaus must NOT automatically be called safe.
    5. URLhaus checks malware-distribution URLs; it does not establish
       whether a website is a phishing site.
    6. Never claim that a URL was verified if the API check failed.
    7. Give practical safety recommendations.
    8. Do not invent facts.

    Return the result using the required structured format.
    """

    result = structured_llm.invoke(prompt)

    return result

