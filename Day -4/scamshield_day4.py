import re
from langchain.tools import tool

@tool
def extract_urls(message: str) -> list:
    """
    Extract website links from SMS, WhatsApp messages, and emails.
    """
    pattern = r'https?://[^\s<>"\']+|www\.[^\s<>"\']+'

    urls = re.findall(pattern, message)

    cleaned_urls = []

    for url in urls:
        url = url.rstrip(".,!?;:)]}")
        if url not in cleaned_urls:
            cleaned_urls.append(url)

    return cleaned_urls

import requests
from urllib.parse import urlparse

@tool
def check_url_reputation(url: str) -> str:
    """
    Check whether a URL is listed in the URLhaus malware URL database.
    A URL not found in URLhaus is not guaranteed to be safe.
    """

    if not URLHAUS_AUTH_KEY:
        return "URLhaus API key is missing. Reputation check unavailable."

    if url.startswith("www."):
        url = "https://" + url

    parsed = urlparse(url)

    if parsed.scheme not in ["http", "https"] or not parsed.netloc:
        return "Invalid URL format."

    api_url = "https://urlhaus-api.abuse.ch/v1/url/"

    headers = {
        "Auth-Key": URLHAUS_AUTH_KEY
    }

    data = {
        "url": url
    }

    try:
        response = requests.post(
            api_url,
            data=data,
            headers=headers,
            timeout=15
        )

        response.raise_for_status()
        result = response.json()

        status = result.get("query_status")

        if status == "ok":
            return (
                "WARNING: URL FOUND in URLhaus malware database. "
                f"URL: {url}. "
                f"Threat: {result.get('threat', 'Unknown')}. "
                f"Status: {result.get('url_status', 'Unknown')}."
            )

        elif status == "no_results":
            return (
                f"No matching record found for {url} in URLhaus. "
                "This does NOT prove the URL is safe."
            )

        else:
            return f"URLhaus returned status: {status}"

    except requests.exceptions.Timeout:
        return "URLhaus request timed out. Try again later."

    except requests.exceptions.RequestException as e:
        return f"URLhaus connection error: {str(e)}"

    except ValueError:
        return "URLhaus returned an invalid response."

