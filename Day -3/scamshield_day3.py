from langchain_groq import ChatGroq

llm = ChatGroq(
    model="openai/gpt-oss-120b",
    temperature=0.3
)

print("ScamShield LLM connected successfully!")

from langchain_core.prompts import ChatPromptTemplate

SYSTEM = """
ROLE:
You are ScamShield, an AI cybersecurity assistant.

PURPOSE:
Detect possible scam and phishing messages.

RULES:
1. Identify suspicious words and urgency.
2. Explain possible phishing attempts.
3. Identify suspicious URLs from the message.
4. Never ask users to share passwords, PINs or OTPs.
5. Do not claim to verify live URL reputation.
6. Suggest safe actions.

FORMAT:
Give a clear explanation using:
- Risk Level
- Scam Type
- Suspicious Indicators
- Recommended Action
"""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    ("human", "{question}")
])

print("Prompt template created!")

from langchain_core.output_parsers import StrOutputParser

chain = prompt | llm | StrOutputParser()

print("ScamShield chain created successfully!")

result = chain.invoke({
    "question": "Your bank account will be blocked today. Share your OTP immediately."
})

print(result)

from langchain_core.prompts import (
    ChatPromptTemplate,
    MessagesPlaceholder
)

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),
    ("human", "{question}")
])

chain = prompt | llm | StrOutputParser()

history = []

def ask(question: str) -> str:

    answer = chain.invoke({
        "history": history,
        "question": question
    })

    history.extend([
        ("human", question),
        ("ai", answer)
    ])

    return answer

print(ask("My name is Varsha. I received a suspicious bank message."))

print(ask("What is my name?"))

import csv

test_data = [
    {
        "question": "Your bank account is blocked. Share your OTP.",
        "must_include": "OTP"
    },
    {
        "question": "You won a lottery. Pay a processing fee to claim it.",
        "must_include": "fee"
    },
    {
        "question": "Your electricity bill is due. Pay through the official app.",
        "must_include": "official"
    },
    {
        "question": "Share your password to receive a prize.",
        "must_include": "password"
    },
    {
        "question": "Your college exam starts at 9 AM tomorrow.",
        "must_include": "exam"
    }
]

with open("/content/scamshield_tests.csv", "w", newline="") as file:

    writer = csv.DictWriter(
        file,
        fieldnames=["question", "must_include"]
    )

    writer.writeheader()
    writer.writerows(test_data)

print("CSV test file created!")

def run_tests(path="/content/scamshield_tests.csv"):

    with open(path, "r") as file:
        rows = list(csv.DictReader(file))

    passed = 0

    for row in rows:

        answer = chain.invoke({
            "history": [],
            "question": row["question"]
        })

        ok = row["must_include"].lower() in answer.lower()

        if ok:
            passed += 1

        print(
            "PASS" if ok else "CHECK",
            "|",
            row["question"],
            "->",
            answer[:100]
        )

        print("-" * 60)

    print(f"\n{passed}/{len(rows)} tests passed")

run_tests()

