def analyze_message(message):

    prompt = f"""
    Analyze this message for scam or phishing signs.

    Return ONLY valid JSON with these keys:
    {{
        "is_suspicious": true,
        "risk_level": "High",
        "scam_type": "Phishing",
        "indicators": [],
        "suspicious_urls": [],
        "recommended_action": ""
    }}

    Message: {message}
    """

    response = client.chat.completions.create(
        model=MODEL,
        messages=[
            {
                "role": "system",
                "content": "You are ScamShield, a cybersecurity scam detection assistant. Return only valid JSON. Do not claim to have verified a URL's live reputation."
            },
            {
                "role": "user",
                "content": prompt
            }
        ],
        temperature=0
    )

    result = response.choices[0].message.content

    try:
        data = json.loads(result)
        return data

    except json.JSONDecodeError:
        print("Invalid JSON response:")
        print(result)
        return None

